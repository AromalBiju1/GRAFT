/**
 * Research dossier, citation formatting, and export utilities for GRAFT.
 */

export function cleanKey(str) {
  if (!str) return "ref";
  return String(str)
    .replace(/[^a-zA-Z0-9_-]/g, "_")
    .replace(/^_+|_+$/g, "")
    .toLowerCase() || "ref";
}

export function formatBibTeX(evidence = []) {
  if (!evidence || !evidence.length) {
    return "% No supporting evidence records available for export.";
  }

  const seen = new Set();
  const entries = [];

  evidence.forEach((ev, idx) => {
    const rawSource = ev.source || ev.document_id || `source_${idx + 1}`;
    const key = `${cleanKey(rawSource)}_${ev.level ?? 0}_${idx + 1}`;
    if (seen.has(key)) return;
    seen.add(key);

    const title = ev.source ? `Document Source: ${ev.source}` : `Corpus Passage ${idx + 1}`;
    const levelStr =
      ev.level === 0 ? "RAPTOR Level 0 (Leaf Passage)" :
      ev.level === 1 ? "RAPTOR Level 1 (Cluster Summary)" :
      ev.level === 2 ? "RAPTOR Level 2 (Root Document Summary)" : `Tree Level ${ev.level ?? 0}`;
    const scoreStr = Number.isFinite(ev.score) ? (ev.score * 100).toFixed(1) + "% similarity" : "N/A";
    const snippet = (ev.text || "").replace(/[\r\n]+/g, " ").slice(0, 160).replace(/["{}]/g, "");

    entries.push(`@misc{${key},
  title = {${title}},
  author = {GRAFT Adaptive Retrieval Engine},
  year = {2026},
  note = {${levelStr}, ${scoreStr}. Excerpt: "${snippet}..."}
}`);
  });

  return entries.join("\n\n");
}

export function formatAPA(evidence = []) {
  if (!evidence || !evidence.length) {
    return "No reference records available.";
  }

  const seen = new Set();
  const list = [];

  evidence.forEach((ev, idx) => {
    const rawSource = ev.source || ev.document_id || `Source [${idx + 1}]`;
    if (seen.has(rawSource)) return;
    seen.add(rawSource);

    const levelStr =
      ev.level === 0 ? "Leaf passage" :
      ev.level === 1 ? "Cluster summary" :
      ev.level === 2 ? "Root summary" : `Level ${ev.level ?? 0}`;
    const pageStr = Number.isFinite(ev.page) ? `, p. ${ev.page}` : "";

    list.push(`${rawSource}. (2026). Retrieved from GRAFT Knowledge Base [${levelStr}${pageStr}].`);
  });

  return list.join("\n\n");
}

export function exportMarkdownReport({ query, text, routing, evidence, moduleResults, latencyMs }) {
  const dateStr = new Date().toLocaleString();
  const complexity = routing?.complexity ? routing.complexity.toUpperCase() : "STANDARD";
  const depth = routing?.retrieval_depth ?? 0;
  const modulesFired = routing?.activated_modules?.join(", ") || "none";

  let md = `# Research Dossier: ${query || "Knowledge Base Analysis"}\n\n`;
  md += `*Generated by GRAFT Adaptive RAG Engine • ${dateStr}*\n\n`;
  md += `---\n\n`;

  md += `## 1. Executive Summary\n\n`;
  md += `${text || "No synthesis generated."}\n\n`;

  md += `## 2. Gated Routing & Architecture Telemetry\n\n`;
  md += `- **Query Complexity Classification:** \`${complexity}\` (confidence: ${routing?.confidence ? (routing.confidence * 100).toFixed(1) + "%" : "N/A"})\n`;
  md += `- **RAPTOR Tree Retrieval Depth:** \`Level ${depth}\` (${depth === 0 ? "Leaves only" : depth === 1 ? "Leaves + Cluster Summaries" : "Full Tree to Root"})\n`;
  md += `- **Activated Specialist Modules:** ${modulesFired}\n`;
  if (latencyMs) {
    md += `- **Execution Latency:** \`${latencyMs} ms\`\n`;
  }
  md += `\n`;

  if (moduleResults && moduleResults.length) {
    md += `## 3. Specialist Reasoning Module Findings\n\n`;
    moduleResults.forEach((mod) => {
      const name = (mod.module || "Module").replace(/_/g, " ").toUpperCase();
      md += `### ${name}\n`;
      if (typeof mod.result === "string") {
        md += `${mod.result}\n\n`;
      } else if (mod.result && typeof mod.result === "object") {
        md += `\`\`\`json\n${JSON.stringify(mod.result, null, 2)}\n\`\`\`\n\n`;
      }
    });
  }

  if (evidence && evidence.length) {
    md += `## 4. Primary Evidence & Source Provenance\n\n`;
    evidence.forEach((item, idx) => {
      const src = item.source || item.document_id || "Corpus Document";
      const lvl = item.level === 0 ? "Level 0 (Leaf)" : item.level === 1 ? "Level 1 (Summary)" : `Level ${item.level ?? 0}`;
      const score = Number.isFinite(item.score) ? ` • Score: ${(item.score * 100).toFixed(1)}%` : "";
      const page = Number.isFinite(item.page) ? ` • Page: ${item.page}` : "";

      md += `**[${idx + 1}] ${src}** (${lvl}${score}${page})\n`;
      if (item.text) {
        md += `> ${item.text.replace(/\n/g, "\n> ")}\n\n`;
      } else {
        md += `\n`;
      }
    });
  }

  md += `---\n*End of Research Dossier*\n`;
  return md;
}

export async function copyToClipboard(content) {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(content);
      return true;
    }
  } catch {}
  // Fallback
  const ta = document.createElement("textarea");
  ta.value = content;
  ta.style.position = "fixed";
  ta.style.left = "-9999px";
  document.body.appendChild(ta);
  ta.select();
  try {
    document.execCommand("copy");
    document.body.removeChild(ta);
    return true;
  } catch {
    document.body.removeChild(ta);
    return false;
  }
}
